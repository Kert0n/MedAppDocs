"""Как складывалась схема подтверждения операций (раздел 8 текста выступления).

Источники: PR сервера #87, #89 (закрыты), #100, #146 и issue #145; PR клиента #9, #10 и issue #2.
"""
from svgkit import Canvas, BLUE, YELLOW, SRV, PALE, GREY

W = 1600
c = Canvas(W)
steps = [
    ('Сервер', 'Память результатов', ['на минуты в памяти', 'процесса']),
    ('Сервер', 'Запись после фиксации', ['память помнила попытку:', 'переживала откат']),
    ('Телефон', 'Без ручной сверки', ['«исход неизвестен» не', 'становится работой человека']),
    ('Телефон', 'Читать, потом писать', ['повтор — тем же запросом', 'и тем же номером']),
    ('Сервер', 'Разведены отказы', ['«устарело» и «другое тело', 'под тем же номером»']),
    ('Оба', 'Журнал не в базе', ['квитанции копили бы частоту', 'действий; сутки в памяти']),
]
X0, gap, top = 30, 16, 60
bw = (W - 2 * X0 - gap * (len(steps) - 1)) / len(steps)
c.line(X0, top + 20, W - X0, top + 20, width=3, arrow=True)
for i, (who, title, rows) in enumerate(steps):
    x = X0 + i * (bw + gap)
    fill = SRV if who == 'Сервер' else YELLOW if who == 'Телефон' else PALE
    c.rect(x, top + 50, bw, 170, fill=fill)
    c.text(x + 16, top + 84, who, 16, color=GREY)
    c.text(x + 16, top + 116, title, 20, 'bold')
    c.lines(x + 16, top + 150, rows, 16, step=24)
c.text(X0, top - 10, 'Как складывалась схема подтверждения операций', 24, 'bold')
c.save('12-journal.svg', top + 240)

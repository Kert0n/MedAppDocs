"""Что знает сервер и что остаётся на телефоне, и чего это стоило (раздел 8 текста выступления).

Источник: схема сервера db/schema.sql, Room-схема клиента (package_details: «сведения, которых
сервер не знает») и ARCHITECTURE.md сервера.
"""
from svgkit import Canvas, BLUE, YELLOW, SRV, PALE, WHITE, GREY

W = 1600
c = Canvas(W)
X0, gap = 30, 40
cw = (W - 2 * X0 - gap) / 2
server = ['учётная запись: идентификатор и хеш ключа', 'кто состоит в общей аптечке (без имён)',
          'лекарства общих аптечек: название, форма, остаток, версия',
          'брони каждого участника, их сумма и версия', 'справочник препаратов']
phone = ['названия и места аптечек', 'сроки годности, цены, заметки', 'курсы, расписание, источники',
         'журнал приёмов', 'напоминания', 'очередь изменений для сервера', 'местные аптечки целиком']
top = 20
h = 64 + 34 * max(len(server), len(phone)) + 20
for x, title, rows, fill in ((X0, 'Сервер знает', server, SRV),
                             (X0 + cw + gap, 'Остаётся только на телефоне', phone, YELLOW)):
    c.rect(x, top, cw, h, fill=fill)
    c.text(x + 28, top + 44, title, 26, 'bold')
    c.lines(x + 28, top + 92, rows, 20, step=34)

y = top + h + 50
c.text(X0, y, 'Цена приватности', 24, 'bold')
costs = [['доступ проверяется', 'в каждом запросе:', 'чужое и несуществующее', 'неотличимы'],
         ['команда удерживает', 'доступ до конца:', 'участника могут', 'исключить посреди'],
         ['сервер получает итоги,', 'а не события;', 'обновление приходит', 'полным снимком'],
         ['журнал повторов', 'только в памяти:', 'в базе он копил бы', 'частоту действий'],
         ['утраченный ключ', 'не восстановить:', 'сервер не знает,', 'чей он был']]
kw = (W - 2 * X0 - 4 * 20) / 5
y += 20
for i, rows in enumerate(costs):
    x = X0 + i * (kw + 20)
    c.rect(x, y, kw, 150, fill=PALE)
    c.lines(x + 18, y + 38, rows, 18, step=27)
c.save('10-knowledge.svg', y + 170)

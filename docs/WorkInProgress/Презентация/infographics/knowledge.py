"""Что знает сервер и что остаётся на телефоне, и что из этого следует (раздел 8 текста выступления).

Источник: схема сервера db/schema.sql, Room-схема клиента (package_details: «сведения, которых
сервер не знает») и ARCHITECTURE.md сервера.
"""
from svgkit import Canvas, BLUE, YELLOW, SRV, PALE, WHITE, GREY

W = 1600
c = Canvas(W)
X0, gap = 30, 40
cw = (W - 2 * X0 - gap) / 2
server = ['учётная запись: идентификатор и хеш ключа', 'кто состоит в общей аптечке (без имён)',
          'упаковки общих аптечек: название, форма, остаток', 'брони каждого участника',
          'справочник препаратов', 'ни одной даты']
phone = ['названия и места аптечек', 'сроки годности, цены, заметки', 'курсы, расписание, источники',
         'журнал приёмов', 'напоминания', 'поручения серверу', 'местные аптечки целиком']
top = 20
h = 64 + 34 * max(len(server), len(phone)) + 20
for x, title, rows, fill in ((X0, 'Сервер знает', server, SRV),
                             (X0 + cw + gap, 'Остаётся только на телефоне', phone, YELLOW)):
    c.rect(x, top, cw, h, fill=fill)
    c.text(x + 28, top + 44, title, 26, 'bold')
    c.lines(x + 28, top + 92, rows, 20, step=34)

y = top + h + 50
c.text(X0, y, 'Следствия', 24, 'bold')
costs = [['Конфликт решает телефон', 'сервер не знает курсов,', 'бронь для него — заявка,', 'чужую бронь стережёт клиент'],
         ['Итог вместо событий', 'расход приращением,', 'бронь абсолютом —', 'одним запросом на упаковку'],
         ['Подтверждение без базы', 'журнал повторов в памяти', 'не дольше суток: таблица', 'копила бы частоту действий']]
kw = (W - 2 * X0 - 2 * 20) / 3
y += 20
for i, rows in enumerate(costs):
    x = X0 + i * (kw + 20)
    c.rect(x, y, kw, 150, fill=PALE)
    c.text(x + 18, y + 38, rows[0], 20, 'bold')
    c.lines(x + 18, y + 70, rows[1:], 18, step=27)
c.save('10-knowledge.svg', y + 170)

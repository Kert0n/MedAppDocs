# coding: utf-8
"""Карта возможностей: что делает программа (раздел 2 текста выступления)."""
from svgkit import Canvas, BLUE, PALE, WHITE, GREY

blocks = [
    ('Учёт лекарств', ['аптечки там, где', 'лекарства лежат:', 'дом, дача, сумка', '', 'остаток, срок, место', '',
                       'ввод со справочником', 'или сканером кода']),
    ('Лечение', ['курс как у врача:', 'доза, дни, время,', 'сколько доз выпить', '', 'источники по порядку:',
                 'сначала то, что', 'истекает раньше']),
    ('Напоминания', ['приходят вовремя,', 'и после перезагрузки', '', 'ответ прямо', 'из уведомления', '',
                     '«принял» списывает', 'дозу из конкретного', 'лекарства']),
    ('Общая аптечка', ['приглашение', 'QR или кодом', '', 'один запас на', 'несколько телефонов', '',
                       'курс каждого', 'бронирует свою часть']),
    ('Отчёты', ['что есть сейчас', '', 'сколько уйдёт', 'до выбранной даты', '', 'сколько истрачено',
                'за период']),
]
W, gap, x0, top = 1600, 20, 20, 20
cw = (W - 2 * x0 - gap * (len(blocks) - 1)) / len(blocks)
c = Canvas(W)
for i, (title, rows) in enumerate(blocks):
    x = x0 + i * (cw + gap)
    c.rect(x, top, cw, 330, fill=PALE)
    c.rect(x, top, cw, 58, fill=BLUE, stroke=BLUE)
    c.text(x + cw / 2, top + 38, title, 24, 'bold', WHITE, 'middle')
    c.lines(x + 20, top + 96, rows, 19, step=25)
y = top + 350
c.rect(x0, y, W - 2 * x0, 54, fill=WHITE, dash='6 5')
c.text(W / 2, y + 35, 'Не назначает лечение и не заменяет лекарства: ведёт учёт и напоминает', 21, color=GREY,
       anchor='middle')
c.save('00-capabilities.svg', y + 74)
